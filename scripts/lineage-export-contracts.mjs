import assert from 'node:assert/strict';
import { existsSync } from 'node:fs';
assert.ok(existsSync('scripts/finalize-lineage.mjs'), 'static lineage finalizer exists');
const { stripRuntime, inlineStyles, fingerprintTimeline } = await import('./finalize-lineage.mjs');
assert.equal(typeof fingerprintTimeline,'function','timeline dependency must be content-addressed');
const first=fingerprintTimeline("import './timeline.mjs';",'export const n=1;');
const second=fingerprintTimeline("import './timeline.mjs';",'export const n=2;');
assert.notEqual(first.name,second.name);
assert.ok(first.source.includes(first.dependency));
assert.notEqual(first.dependency,second.dependency);
assert.equal(typeof inlineStyles,'function','inline the island CSS to avoid a critical round trip');
assert.equal(await inlineStyles('<link rel="stylesheet" href="/base/_next/static/css/a.css"/>',async path=>{assert.equal(path,'/_next/static/css/a.css');return 'h1{color:blue}';}),'<style data-lineage-critical>h1{color:blue}</style>');
const html='<html><head><link rel="preload" as="script" href="/base/_next/x.js"/><link rel="stylesheet" href="/base/_next/style.css"/></head><body><main data-lineage="true">Archive</main><script src="/base/_next/x.js"></script><script>self.__next_f.push([1,"/lineage/viewer.mjs"])</script><script type="module" src="/base/lineage/viewer.mjs"></script></body></html>';
const output=stripRuntime(html);
assert.ok(output.includes('stylesheet'));
assert.ok(output.includes('Archive'));
assert.ok(output.includes('/base/lineage/viewer.mjs'));
assert.ok(!output.includes('__next_f'));
assert.ok(!output.includes('/base/_next/x.js'));
assert.equal(stripRuntime(output),output);
assert.throws(()=>stripRuntime('<main>other route</main>'));
console.log('PASS: only the no-hydration lineage route loses its runtime; CSS and viewer preserved');
