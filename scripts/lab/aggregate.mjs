#!/usr/bin/env node
/**
 * Quackles Lab aggregation (#53). Reads every receipt in a run directory and writes summary.csv + summary.md.
 * No composite score, no ranking, no averaging across SHAs/profiles: one row per cell, medians with min..max.
 *
 *   node scripts/lab/aggregate.mjs results/<run-id> [--out experiments/results/<run-id>]
 */
import fs from "node:fs";
import path from "node:path";
import { checkReceipt, summarize, SUMMARY_METRICS } from "./lib.mjs";

const dir = process.argv[2];
if (!dir || !fs.existsSync(dir)) {
  console.error("usage: node scripts/lab/aggregate.mjs results/<run-id> [--out DIR]");
  process.exit(2);
}
const outFlag = process.argv.indexOf("--out");
const outDir = outFlag > 0 ? process.argv[outFlag + 1] : dir;
const manifest = fs.existsSync(path.join(dir, "run.json")) ? JSON.parse(fs.readFileSync(path.join(dir, "run.json"), "utf8")) : null;
const receipts = fs.readdirSync(dir).filter((f) => f.endsWith(".json") && f !== "run.json").sort()
  .map((f) => ({ f, r: JSON.parse(fs.readFileSync(path.join(dir, f), "utf8")) }));
const invalid = receipts.map(({ f, r }) => [f, checkReceipt(r)]).filter(([, p]) => p.length);
if (invalid.length) {
  for (const [f, p] of invalid) console.error(`${f}: ${p.join("; ")}`);
  process.exit(1);
}
const cells = summarize(receipts.map(({ r }) => r));

const fmt = (s) => (s ? (s.min === s.max ? `${s.median}` : `${s.median} (${s.min}..${s.max})`) : "n/a");
const csvCell = (v) => (/[",\n]/.test(String(v)) ? `"${String(v).replace(/"/g, '""')}"` : String(v));
const header = ["branch", "sha", "scenario", "mode", "profile", "status", "trials", "pass", "fail", "notRun",
  ...SUMMARY_METRICS.flatMap((m) => [`${m}_median`, `${m}_min`, `${m}_max`]), "failures", "notRunReasons"];
const csv = [header.join(","), ...cells.map((c) => [
  c.branch, c.sha, c.scenario, c.mode, c.profile, c.status, c.trials, c.pass, c.fail, c.notRun,
  ...SUMMARY_METRICS.flatMap((m) => (c.stats[m] ? [c.stats[m].median, c.stats[m].min, c.stats[m].max] : ["", "", ""])),
  c.failures.join(" | "), c.notRunReasons.join(" | "),
].map(csvCell).join(","))].join("\n") + "\n";

const first = receipts[0]?.r;
const env = first?.environment ?? {};
const md = [
  `# Quackles Lab run \`${manifest?.runId ?? path.basename(dir)}\``,
  "",
  "Generated by `scripts/lab/aggregate.mjs`. Cells are sorted by receipt file name: **this is not a ranking**. Medians over valid trials with (min..max); `n/a` = not measured (see receipt `metricNotes`), never zero.",
  "",
  "## Pins",
  "",
  `- Command: \`${manifest?.command ?? "unknown"}\``,
  `- Harness: \`${first?.harness?.sha ?? "?"}\`${first?.harness?.dirty ? " (**uncommitted harness changes**)" : ""}`,
  `- Tape: \`${first?.scenario?.tape}\` \`${first?.scenario?.tapeHash}\` (seed ${first?.scenario?.seed})`,
  `- Assets: ${first?.fixture?.origin ?? "?"}`,
  `- Browser: ${env.browser} headless=${env.headless}; GPU: ${env.gpu ?? "unknown"} (${env.gpuFlags})`,
  `- Host: ${env.device}; node ${env.node}; idle rAF ${env.idleRafMs} ms`,
  `- Network: ${env.network}; cache: ${env.cache}; instrumentation: ${env.instrumentation}`,
  manifest ? `- Trial order (seeded random): ${manifest.order.map((o) => o.join(" > ")).join(" / ")}` : null,
  "",
  "## Builds",
  "",
  "| ref | sha | build | fixture |",
  "|---|---|---|---|",
  ...(manifest?.builds ?? []).map((b) => {
    const f = receipts.find(({ r }) => r.sha === b.sha && r.fixture?.id)?.r.fixture;
    return `| \`${b.ref}\` | \`${b.sha}\` | ${b.status}${b.reason ? `: ${b.reason}` : ""} | ${f ? `${f.id} ${f.width}x${f.height} tile ${f.tileSize} ${f.masterHash?.slice(0, 19)}…` : "n/a"} |`;
  }),
  "",
  "## Cells",
  "",
  "| branch | sha | mode | profile | status | trials P/F/NR | rAF p50 | rAF p95 | rAF p99 | max frame | >33 ms | >50 ms | first paint (app) | time to sharp | input->camera | requests | bytes | aborts | stale work | blank polls | decoded peak | surface est. |",
  "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|",
  ...cells.map((c) => `| \`${c.branch}\` | \`${c.sha.slice(0, 12)}\` | ${c.mode} | ${c.profile} | **${c.status}** | ${c.pass}/${c.fail}/${c.notRun} | ${["rafP50Ms", "rafP95Ms", "rafP99Ms", "maxFrameMs", "framesOver33Ms", "framesOver50Ms", "firstPaintReportedMs", "timeToSharpMs", "inputToCameraMs", "requests", "transferredBytes", "abortCount", "staleWorkCount", "blankFrames", "decodedPeakBytes", "gpuResidentBytesEstimate"].map((m) => fmt(c.stats[m])).join(" | ")} |`),
  "",
  ...cells.filter((c) => c.failures.length || c.notRunReasons.length).flatMap((c) => [
    `### \`${c.branch}\` ${c.mode} ${c.profile}`, "",
    ...c.failures.map((f) => `- FAIL: ${f}`), ...[...new Set(c.notRunReasons.map((f) => f.replace(/\d+ x 404/, "N x 404")))].map((f) => `- not covered: ${f}`), "",
  ]),
  "## Units and caveats",
  "",
  "- PASS means the smoke correctness gates in `validation.passed` held. It is not product acceptance, a feel verdict or a ranking.",
  "- Times in ms; bytes are loopback body+headers (not CDN wire bytes). `first paint (app)` is the app-reported first paint, not a pixel-verified correct visual.",
  "- `input->camera` = wheel `event.timeStamp` to the first rAF whose camera transform changed. Not photon latency; no GPU completion.",
  "- `surface est.` = canvas backing-store estimate, not measured GPU memory. `blank polls` are 50 ms samples, not every frame.",
  "- Headless desktop Chromium on a shared host. No physical-device, emulated-vs-physical, or feel claim follows from these numbers.",
  "",
].filter((l) => l !== null).join("\n");

fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, "summary.csv"), csv);
fs.writeFileSync(path.join(outDir, "summary.md"), md);
console.log(`${receipts.length} receipts -> ${cells.length} cells -> ${path.join(outDir, "summary.{md,csv}")}`);
